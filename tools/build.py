"""Build the single-file CleanGEO site.

Sources live in assets/*.js (ES modules) and assets/style.css; the page shell is
assets/page.template.html. This script inlines everything into index.html so the
site works from GitHub Pages, from file://, and inside any webview — no module
loading, no CORS, no extra requests.

    python tools/build.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / 'assets'
ORDER = ['blocklist.js', 'search.js', 'proxy.js', 'store.js', 'app.js']


def strip_module_syntax(src: str) -> str:
    """Turn an ES module into plain script content (imports hoisted away)."""
    out, lines, i = [], src.split('\n'), 0
    while i < len(lines):
        line = lines[i]
        stripped = line.strip()
        if stripped.startswith('import '):
            # skip the whole (possibly multi-line) import statement
            while i < len(lines):
                if re.search(r"from\s+['\"][^'\"]+['\"]\s*;?\s*$", lines[i]) or \
                   re.match(r"^import\s+['\"][^'\"]+['\"];?\s*$", lines[i].strip()):
                    break
                i += 1
            i += 1
            continue
        if stripped.startswith('export default '):
            line = line.replace('export default ', 'const __default = ', 1)
        elif stripped.startswith('export '):
            line = re.sub(r'^(\s*)export\s+', r'\1', line)
        out.append(line)
        i += 1
    return '\n'.join(out)


def build_js() -> str:
    parts = []
    for name in ORDER:
        src = (ASSETS / name).read_text(encoding='utf-8')
        body = strip_module_syntax(src)
        parts.append(f'/* ==== src: assets/{name} ==== */\n{body}')
    banner = (
        "/* CleanGEO — generated by tools/build.py from assets/*.js.\n"
        "   Edit the sources, not this block, then re-run:  python tools/build.py */\n"
        "(function () {\n'use strict';\n"
    )
    return banner + '\n\n'.join(bodies_safe(parts)) + '\n})();\n'


def bodies_safe(parts):
    """Guard against accidental top-level redeclarations between modules."""
    seen = {}
    out = []
    for part in parts:
        for m in re.finditer(r'^(?:const|let|class)\s+([A-Za-z_$][\w$]*)', part, re.M):
            name = m.group(1)
            seen[name] = seen.get(name, 0) + 1
    dupes = {k for k, v in seen.items() if v > 1}
    if dupes:
        raise SystemExit('Duplicate top-level names across modules: ' + ', '.join(sorted(dupes)))
    return parts


def main():
    js = build_js()
    css = (ASSETS / 'style.css').read_text(encoding='utf-8')
    tpl = (ASSETS / 'page.template.html').read_text(encoding='utf-8')

    html = tpl.replace('/*__CSS__*/', css).replace('/*__JS__*/', js)

    leftover = re.findall(r'^\s*(?:import|export)\s', js, re.M)
    if leftover:
        raise SystemExit(f'{len(leftover)} module keywords left in the bundle')

    (ROOT / 'index.html').write_text(html, encoding='utf-8')
    print(f'index.html   {len(html):>7} bytes')
    print(f'css inlined  {len(css):>7} bytes')


if __name__ == '__main__':
    main()
